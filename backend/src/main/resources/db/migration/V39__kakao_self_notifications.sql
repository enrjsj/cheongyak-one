-- One configured owner only. Tokens are AES-GCM ciphertext; OAuth state/session are hashes.
CREATE TABLE KAKAO_SELF_CONNECTION (
    ID INTEGER PRIMARY KEY CHECK (ID = 1),
    MEMBER_ID BIGINT REFERENCES APP_MEMBER(ID) ON DELETE SET NULL,
    GENERATION VARCHAR(36) NOT NULL,
    ACCESS_TOKEN VARCHAR(4096), REFRESH_TOKEN VARCHAR(4096),
    ACCESS_EXPIRES_AT TIMESTAMP WITH TIME ZONE, REFRESH_EXPIRES_AT TIMESTAMP WITH TIME ZONE,
    CONNECTED_AT TIMESTAMP WITH TIME ZONE,
    CUTOFF_ID BIGINT DEFAULT 0 NOT NULL,
    RECONNECT_REQUIRED BOOLEAN DEFAULT FALSE NOT NULL,
    STATE_HASH VARCHAR(64), SESSION_HASH VARCHAR(64), STATE_EXPIRES_AT TIMESTAMP WITH TIME ZONE,
    LEASE_ID VARCHAR(36), LEASE_UNTIL TIMESTAMP WITH TIME ZONE,
    LAST_TEST_AT TIMESTAMP WITH TIME ZONE,
    LAST_SENT_AT TIMESTAMP WITH TIME ZONE, LAST_DELIVERY_STATUS VARCHAR(32)
);
INSERT INTO KAKAO_SELF_CONNECTION (ID, GENERATION) VALUES (1, 'initial');
CREATE TABLE KAKAO_SELF_RECEIPT (
    NOTIFICATION_ID BIGINT PRIMARY KEY REFERENCES MEMBER_NOTIFICATION(ID) ON DELETE CASCADE,
    ATTEMPTED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    OUTCOME VARCHAR(32) NOT NULL CHECK (OUTCOME IN ('UNKNOWN','ACCEPTED','RECONNECT_REQUIRED','RATE_LIMITED','REJECTED','PROVIDER_UNAVAILABLE','INVALID_RESPONSE'))
);
